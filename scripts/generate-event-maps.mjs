/*
 * Generates the event target → event map pairs from TypeScript's own DOM and web worker declarations, so that
 * `addReversibleEventListener` knows every typed event target, plus a type check asserting that each target resolves
 * to its own event map.
 *
 * Every event target in TypeScript's libs declares its typed events the same way:
 *   addEventListener<K extends keyof HTMLElementEventMap>(type: K, listener: (this: HTMLElement, ...
 * Only targets that exist as global classes are kept — the library looks them up through `globalThis`.
 *
 * usage: node scripts/generate-event-maps.mjs [--check]
 *   --check  exit non-zero if the committed files differ from what the installed TypeScript version produces
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
/* asked through the compiler API: the `typescript` package may be an API shim that ships no lib files of its own */
const typescriptLib = dirname(createRequire(import.meta.url)('typescript').getDefaultLibFilePath({}));

/**
 * TypeScript lib files to read, the type check file generated for each environment, and pairs every lib must
 * contain (a guard against a change in TypeScript's lib format silently producing an incomplete list).
 */
const environments = [
	{
		lib: 'lib.dom.d.ts',
		check: 'test/environments/dom/eventMaps.generated.ts',
		expected: { HTMLElement: 'HTMLElementEventMap', Window: 'WindowEventMap', WebSocket: 'WebSocketEventMap' },
	},
	{
		lib: 'lib.webworker.d.ts',
		check: 'test/environments/webworker/eventMaps.generated.ts',
		expected: { DedicatedWorkerGlobalScope: 'DedicatedWorkerGlobalScopeEventMap', WebSocket: 'WebSocketEventMap' },
	},
];
const sourceFile = 'src/eventMaps.generated.ts';

const header = (...lines) =>
	[
		'/*',
		' * Generated by scripts/generate-event-maps.mjs — do not edit.',
		...lines.map(line => ` * ${line}`),
		' */',
	].join('\n');

const extractTargets = lib => {
	const source = readFileSync(resolve(typescriptLib, lib), 'utf8');
	const globalClasses = new Set(
		[...source.matchAll(/^declare var (\w+): \{\s*\n\s*prototype: \1;/gm)].map(([, name]) => name)
	);
	const pairs = new Map();
	for (const [, map, target] of source.matchAll(
		/addEventListener<K extends keyof (\w+)>\(type: K, listener: \(this: (\w+), ev: /g
	)) {
		if (globalClasses.has(target)) pairs.set(target, map);
	}
	return pairs;
};

const assertExpected = (lib, pairs, expected) => {
	for (const [target, map] of Object.entries(expected)) {
		if (map !== pairs.get(target)) throw new Error(`${lib}: expected ${target} → ${map}, lib format may have changed`);
	}
};

const compareTargets = ([a], [b]) => a.localeCompare(b);

const renderSource = pairs => `${header(
	"Every global event target in TypeScript's DOM and web worker libs, paired with its event map.",
	'Regenerate with `npm run generate:event-maps` after upgrading TypeScript — `npm test` fails while this is outdated.'
)}
import type { GlobalInstance } from './environment';

export type EventMapMap =
${pairs.map(([target, map]) => `\t| [GlobalInstance<'${target}'>, ${map}]`).join('\n')};

/*
 * Event maps are interfaces, not values, so they cannot be looked up through \`globalThis\`. Empty declarations make
 * their names resolve everywhere: where the environment provides them, these merge with the real maps (including
 * any augmentations, such as custom events a bundler adds to \`WindowEventMap\`); elsewhere they stay empty and unused.
 */
/* eslint-disable @typescript-eslint/no-empty-object-type */
declare global {
${[...new Set(pairs.map(([, map]) => map))]
	.sort()
	.map(map => `\tinterface ${map} {}`)
	.join('\n')}
}
/* eslint-enable @typescript-eslint/no-empty-object-type */
`;

/*
 * Equivalence is checked as mutual assignability: the resolved map merges the maps of all matching supertypes, so it is
 * equivalent to, but not identical with, the target's own map.
 */
const renderCheck = pairs => `${header(
	'Asserts that every event target resolves to an event map equivalent to the one its own addEventListener uses.'
)}
import { expectTypeOf } from 'expect-type';
import type { EventMapOf } from '../../../src/addReversibleEventListener';

${pairs
	.map(([target, map]) =>
		[
			`expectTypeOf<EventMapOf<${target}>>().toExtend<${map}>();`,
			`expectTypeOf<${map}>().toExtend<EventMapOf<${target}>>();`,
		].join('\n')
	)
	.join('\n')}
`;

const format = async (file, content) =>
	prettier.format(content, { ...(await prettier.resolveConfig(resolve(root, file))), filepath: resolve(root, file) });

/** @returns {Promise<Record<string, string>>} generated file contents, keyed by path relative to the package root */
export const generate = async () => {
	const all = new Map();
	const files = {};
	for (const { lib, check, expected } of environments) {
		const pairs = extractTargets(lib);
		assertExpected(lib, pairs, expected);
		for (const [target, map] of pairs) {
			if (all.has(target) && map !== all.get(target)) {
				throw new Error(`${target} uses ${all.get(target)} in one lib and ${map} in ${lib}`);
			}
			all.set(target, map);
		}
		files[check] = renderCheck([...pairs].sort(compareTargets));
	}
	files[sourceFile] = renderSource([...all].sort(compareTargets));
	for (const file of Object.keys(files)) files[file] = await format(file, files[file]);
	return files;
};

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	const files = await generate();
	if (process.argv.includes('--check')) {
		const outdated = Object.keys(files).filter(file => readFileSync(resolve(root, file), 'utf8') !== files[file]);
		if (outdated.length > 0) {
			console.error(`Outdated: ${outdated.join(', ')}\nRun \`npm run generate:event-maps\`.`);
			process.exit(1);
		}
	} else {
		for (const [file, content] of Object.entries(files)) writeFileSync(resolve(root, file), content);
		console.log(`Generated ${Object.keys(files).join(', ')}`);
	}
}
